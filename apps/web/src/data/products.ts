function p(
  partial: Omit<Product, "updatedAt" | "createdAt" | "isActive" | "discount"> & {
    discount?: number;
  }
): Product {
  const discount =
    partial.discount ??
    (partial.mrp > partial.price
      ? Math.round(((partial.mrp - partial.price) / partial.mrp) * 100)
      : 0);
  return {
    ...partial,
    discount,
    isActive: true,
    createdAt: now,
    updatedAt: now,
  };
}

